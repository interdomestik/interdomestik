export function safeExceptionType(type: unknown): string {
  return typeof type === 'string' && ERROR_CLASSES.has(type) ? type : 'Error';
}

export function safePostgresCode(code: unknown): string | undefined {
  return typeof code === 'string' && POSTGRES_CODES.has(code) ? code : undefined;
}

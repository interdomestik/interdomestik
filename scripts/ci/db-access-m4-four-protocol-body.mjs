// Fixed finite protocol runtime contract, independent of candidate input.
export const PROTOCOL_CONTRACT = [
  'export type M4AssignmentRequest = Readonly<{',
  '  version: 1;',
  "  command: 'm4.ops.assign-owner' | 'm4.legacy.assign-claim' | 'm4.staff.assign-claim';",
  '  operationId: string;',
  '  claimId: string;',
  '  staffId?: string | null;',
  '}>;',
  "const FIELDS = new Set(['version', 'command', 'operationId', 'claimId', 'staffId']);",
  'const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;',
  'function id(value: unknown): value is string {',
  '  return (',
  "    typeof value === 'string' &&",
  '    value.length > 0 &&',
  '    value.length <= 256 &&',
  '    !/[\\u0000-\\u001f\\u007f]/.test(value)',
  '  );',
  '}',
  'export function parseM4AssignmentRequest(serialized: unknown): M4AssignmentRequest | null {',
  "  if (typeof serialized !== 'string' || new TextEncoder().encode(serialized).length > 8192)",
  '    return null;',
  '  try {',
  '    const value: unknown = JSON.parse(serialized);',
  "    if (!value || typeof value !== 'object' || Array.isArray(value)) return null;",
  '    const row = value as Record<string, unknown>;',
  '    if (',
  '      Object.keys(row).some(key => !FIELDS.has(key)) ||',
  '      row.version !== 1 ||',
  '      !id(row.claimId) ||',
  "      typeof row.operationId !== 'string' ||",
  '      !UUID.test(row.operationId)',
  '    )',
  '      return null;',
  '    if (',
  "      row.command !== 'm4.ops.assign-owner' &&",
  "      row.command !== 'm4.legacy.assign-claim' &&",
  "      row.command !== 'm4.staff.assign-claim'",
  '    )',
  '      return null;',
  "    if (row.command === 'm4.ops.assign-owner' && !id(row.staffId)) return null;",
  "    if (row.command === 'm4.legacy.assign-claim' && row.staffId !== null && !id(row.staffId))",
  '      return null;',
  '    if (',
  "      row.command === 'm4.staff.assign-claim' &&",
  '      row.staffId !== undefined &&',
  '      row.staffId !== null &&',
  '      !id(row.staffId)',
  '    )',
  '      return null;',
  '    return Object.freeze({',
  '      version: 1,',
  '      command: row.command,',
  '      operationId: row.operationId,',
  '      claimId: row.claimId,',
  '      ...(row.staffId === undefined ? {} : { staffId: row.staffId as string | null }),',
  '    });',
  '  } catch {',
  '    return null;',
  '  }',
  '}',
  '',
].join('\n');
